def build_transition(entry: Dict[str, Any]):
    tid = entry["transition_id"]
    repo_name = entry["repo_name"]
    repo_dir = REPO_DIR_MAP[repo_name]
    target_commit = entry["target_commit"]
    pkg_path = entry.get("pkg_path", "")

    # Compute base commit = target_commit~1
    base_commit = subprocess.check_output(
        ["git", "-C", repo_dir, "rev-parse", f"{target_commit}~1"],
        env=GIT_ENV
    ).decode("utf-8").strip()

    entry["base_commit"] = base_commit
    entry["external_pr_url"] = entry["pr_url"]
    entry["track"] = entry.get("track", "TRACK_A_STALE_SENSITIVE")

    # 1. Write spec JSON
    spec_path = os.path.join(SPECS_DIR, f"{tid}.json")
    with open(spec_path, "w", encoding="utf-8") as f:
        json.dump(entry, f, indent=2)

    # 2. Extract git archives for before and after (filtered by pkg_path)
    fixture_dir = os.path.join(FIXTURES_DIR, tid)
    before_dir = os.path.join(fixture_dir, "before")
    after_dir = os.path.join(fixture_dir, "after")
    if os.path.exists(before_dir):
        shutil.rmtree(before_dir)
    if os.path.exists(after_dir):
        shutil.rmtree(after_dir)
    os.makedirs(before_dir, exist_ok=True)
    os.makedirs(after_dir, exist_ok=True)

    # Git archive before
    ps_b = subprocess.Popen(["git", "-C", repo_dir, "archive", base_commit, pkg_path], stdout=subprocess.PIPE, env=GIT_ENV)
    subprocess.check_call(["tar", "-x", "-C", before_dir], stdin=ps_b.stdout)
    ps_b.wait()

    # Git archive after
    ps_a = subprocess.Popen(["git", "-C", repo_dir, "archive", target_commit, pkg_path], stdout=subprocess.PIPE, env=GIT_ENV)
    subprocess.check_call(["tar", "-x", "-C", after_dir], stdin=ps_a.stdout)
    ps_a.wait()

    # 3. Write hidden test and solution files strictly in hidden_tests/ and controls/
    hidden_test_code = entry["hidden_test"]
    ht_dir = os.path.join(fixture_dir, "hidden_tests")
    ctrl_dir = os.path.join(fixture_dir, "controls")
    os.makedirs(ht_dir, exist_ok=True)
    os.makedirs(ctrl_dir, exist_ok=True)
    with open(os.path.join(ht_dir, "test_evaluation.py"), "w", encoding="utf-8") as f:
        f.write(hidden_test_code)

    with open(os.path.join(ctrl_dir, "stale_solution.py"), "w", encoding="utf-8") as f:
        f.write(entry["stale_solution"])
    with open(os.path.join(ctrl_dir, "valid_solution.py"), "w", encoding="utf-8") as f:
        f.write(entry["valid_solution"])

    # 4. Generate diff.patch and pr.json
    ev_dir = os.path.join(DATA_DIR, "external_evidence", tid)
    os.makedirs(ev_dir, exist_ok=True)
    diff_patch = subprocess.check_output(
        ["git", "-C", repo_dir, "diff", base_commit, target_commit],
        env=GIT_ENV
    )
    with open(os.path.join(ev_dir, "diff.patch"), "wb") as f:
        f.write(diff_patch)

    # 5. Generate fixture metadata.json for snapshot purity audit
    primary_file = entry["primary_file"]
    b_file = os.path.join(before_dir, primary_file)
    a_file = os.path.join(after_dir, primary_file)
    b_dig = hashlib.sha256(open(b_file, "rb").read()).hexdigest() if os.path.exists(b_file) else ""
    a_dig = hashlib.sha256(open(a_file, "rb").read()).hexdigest() if os.path.exists(a_file) else ""

    metadata_doc = {
        "transition_id": tid,
        "repo_name": repo_name,
        "repo_url": entry["repo_url"],
        "pr_url": entry["pr_url"],
        "base_commit": base_commit,
        "target_commit": target_commit,
        "pkg_path": pkg_path,
        "changed_files": entry["changed_files"],
        "primary_file": primary_file,
        "symbol": entry["symbol"],
        "file_digest_before": b_dig,
        "file_digest_after": a_dig,
        "stale_sensitive": entry.get("stale_sensitive", True),
        "transition_type": entry.get("transition_type", "API_EVOLUTION"),
        "builder_status": "FIXTURE_EXTRACTED_UNVERIFIED"
    }
    with open(os.path.join(fixture_dir, "metadata.json"), "w", encoding="utf-8") as f:
        json.dump(metadata_doc, f, indent=2)

    print(f"Built fixture & evidence for {tid} ({repo_name}).")


def main():
    batch = sys.argv[1] if len(sys.argv) > 1 else "all"
    if batch == "batch_a":
        cohort = SCALE_COHORT[:10]
    elif batch == "batch_b":
        cohort = SCALE_COHORT[10:]
    else:
        cohort = SCALE_COHORT

    print(f"Building {len(cohort)} scale transitions (Cohort selection: {batch})...")
    for entry in cohort:
        build_transition(entry)

    print(f"\nSuccessfully built {len(cohort)} transitions.")


if __name__ == "__main__":
    main()
